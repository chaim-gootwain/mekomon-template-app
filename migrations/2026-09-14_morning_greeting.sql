-- ============================================================
-- מיגרציה: ברכת "בוקר טוב" יומית לכל הצוות — שלב 1 (inapp)
-- ------------------------------------------------------------
-- מרחיבה את מנוע ההתראות (חובה להריץ קודם את 2026-08-24_alerts_engine.sql
-- ואת 2026-08-30_alerts_engine_v2.sql). הודעה מתוזמנת ראשונה במנוע:
-- מופעלת לפי שעה (לא לפי נתונים) ומיועדת לכל הצוות (לא רק מנהל).
--
-- מה בקובץ:
--   1. עמודת alerts.user_id — התראה ממוענת למשתמש מסוים (null = כמו
--      היום: התראת מנהל). RLS מעודכן: כל משתמש פעיל רואה ומעדכן את
--      ההתראות *שלו*; התראות ללא נמען נשארות מנהל בלבד.
--   2. טבלת morning_messages — מאגר הודעות קטן וניתן לעריכה + זריעה.
--      הודעה יכולה להכיל {city} — מוחלף בשם העיר של המופע
--      (settings.paper_city, נערך במסך ההגדרות ליד שם העיתון).
--   3. מתגים: settings.morning_greeting_enabled (ברירת מחדל '0' — כבוי)
--      ו-settings.paper_city (ריק — עד שממלאים בהגדרות).
--   4. סורק alerts_scan_morning(): פעם בבוקר (לפי תאריך ישראל) יוצר
--      אירוע good_morning + התראת inapp לכל משתמש פעיל, עם רוטציית
--      הודעה לפי יום-בשנה. dedup: good_morning:<user>:<date>.
--   5. עדכון alerts_scan_all() לכלול את הסורק — כך ריצת הכניסה של
--      המנוע (fallback) יוצרת את הברכה גם בלי pg_cron.
--   6. RPC ‏alerts_morning_test() — "שלח בדיקה" למנהל בלבד.
--   7. ג'וב pg_cron יומי ב-05:00 UTC. שים לב: 05:00 UTC = 08:00 בקיץ
--      (IDT) אבל 07:00 בחורף (IST) — cron רץ ב-UTC ואינו מכיר שעון קיץ.
--      נשאר פשוט בכוונה: ג'וב אחד, והפונקציה עצמה שומרת "פעם ביום,
--      לא לפני 05:00 שעון ישראל".
--
-- הרצה: Supabase Dashboard → SQL Editor → הדבק והרץ את כל הקובץ,
-- בכל מופע בנפרד. בטוח להרצה חוזרת (idempotent).
-- המנוע מודיע בלבד — אף פעולה כספית לא מתבצעת מכאן.
-- ============================================================

-- ==================== 1. alerts.user_id + RLS ====================

alter table public.alerts add column if not exists user_id uuid;

do $mig$
begin
  if not exists (select 1 from pg_constraint where conname = 'alerts_user_id_fkey') then
    alter table public.alerts add constraint alerts_user_id_fkey
      foreign key (user_id) references public.profiles(id) on delete cascade;
  end if;
end $mig$;

create index if not exists alerts_user_status_idx on public.alerts (user_id, status);

-- המדיניות הישנה (מנהל רואה הכל) מוחלפת בשלוש ממוקדות:
--   - מנהל: שליטה מלאה בהתראות ללא נמען (ההתנהגות הקיימת);
--   - כל משתמש פעיל: רואה ומעדכן (נקרא/הוסר) את ההתראות הממוענות אליו.
-- המנוע עצמו כותב עם service_role — עוקף RLS, לא מושפע.
drop policy if exists alerts_admin_all on public.alerts;
drop policy if exists alerts_admin_broadcast on public.alerts;
create policy alerts_admin_broadcast on public.alerts
  for all to authenticated
  using (user_id is null and exists (select 1 from public.profiles p
         where p.id = auth.uid() and p.active and p.role = 'admin'))
  with check (user_id is null and exists (select 1 from public.profiles p
              where p.id = auth.uid() and p.active and p.role = 'admin'));

drop policy if exists alerts_own_select on public.alerts;
create policy alerts_own_select on public.alerts
  for select to authenticated
  using (user_id = auth.uid() and exists (select 1 from public.profiles p
         where p.id = auth.uid() and p.active));

drop policy if exists alerts_own_update on public.alerts;
create policy alerts_own_update on public.alerts
  for update to authenticated
  using (user_id = auth.uid() and exists (select 1 from public.profiles p
         where p.id = auth.uid() and p.active))
  with check (user_id = auth.uid());

comment on column public.alerts.user_id
  is 'נמען ההתראה. null = התראת מנהל (ברירת המחדל ההיסטורית); אחרת — רק המשתמש הזה רואה אותה.';

-- ==================== 2. מאגר הודעות הבוקר ====================

create table if not exists public.morning_messages (
  id         bigint generated by default as identity,
  text       text not null,
  active     boolean not null default true,
  created_at timestamptz not null default now()
);

do $mig$
begin
  if not exists (select 1 from pg_constraint where conname = 'morning_messages_pkey') then
    alter table public.morning_messages add constraint morning_messages_pkey primary key (id);
  end if;
end $mig$;

alter table public.morning_messages enable row level security;

drop policy if exists morning_messages_admin_all on public.morning_messages;
create policy morning_messages_admin_all on public.morning_messages
  for all to authenticated
  using (exists (select 1 from public.profiles p
                 where p.id = auth.uid() and p.active and p.role = 'admin'))
  with check (exists (select 1 from public.profiles p
                      where p.id = auth.uid() and p.active and p.role = 'admin'));

grant all on public.morning_messages to anon, authenticated, service_role;

comment on table public.morning_messages
