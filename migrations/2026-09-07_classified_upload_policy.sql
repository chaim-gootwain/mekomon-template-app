-- ============================================================
-- מיגרציה: תיקון באג — העלאת תמונה במודעת לוח מהפורטל נכשלת
-- ------------------------------------------------------------
-- הבעיה: טופס הלוח הציבורי (portal/luach.html) מעלה את התמונה
-- ל-bucket ‏ad-files בנתיב classified/<טלפון>_<זמן>_<קובץ>
-- כמשתמש אנונימי, אבל מדיניות ההעלאה האנונימית הקיימת
-- (2026-09-02_portal_file_upload_policy.sql) מתירה רק נתיבי
-- portal/<טוקן>/... — ולטופס הלוח אין טוקן (הוא פתוח לציבור).
-- לכן כל הגשת מודעת לוח עם תמונה נכשלת בשגיאת RLS.
--
-- הפתרון: מדיניות insert נוספת ל-anon על ad-files, מוגבלת
-- לנתיבים בתבנית המדויקת שהטופס יוצר: classified/ ואחריו
-- 7–15 ספרות טלפון, קו תחתון, חותמת-זמן של לפחות 10 ספרות,
-- וקו תחתון. אין ל-anon קריאה, עדכון או מחיקה — העלאה בלבד,
-- והצפייה נשארת לצוות מחובר בלבד.
--
-- הרצה: Supabase Dashboard → SQL Editor → הדבק והרץ את כל
-- הקובץ, בכל מופע בנפרד. בטוח להרצה חוזרת (idempotent).
-- ============================================================

drop policy if exists "classified_files_insert" on storage.objects;
create policy "classified_files_insert" on storage.objects
  for insert to anon
  with check (
    bucket_id = 'ad-files'
    and name ~ '^classified/[0-9]{7,15}_[0-9]{10,}_'
  );
