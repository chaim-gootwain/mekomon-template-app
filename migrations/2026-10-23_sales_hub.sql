-- ============================================================
-- מיגרציה: מוקד מכירות (sales-hub.js) — מנהל בלבד
-- ------------------------------------------------------------
-- 1. sales_hub_reports — דיווח סוף יום לסוכן (אחד לסוכן ליום).
-- 2. sales_hub_store — מצב המוקד כמפתח → JSONB (סימוני הכשרה,
--    קורסים, משוב אישי, נהלים ותבניות הודעות שנערכו).
-- 3. מתג בהגדרות: sales_hub_enabled ('0' כברירת מחדל).
-- RLS: מנהל פעיל בלבד, בשתי הטבלאות. ל-anon אין גישה.
-- הרצה: Supabase Dashboard → SQL Editor → הדבק והרץ את כל הקובץ,
-- בכל מופע בנפרד. בטוח להרצה חוזרת (idempotent).
-- הפעלה במופע: update public.settings set value = '1' where key = 'sales_hub_enabled';
-- (או בהגדרות → "🎯 מוקד מכירות")
-- ============================================================

-- ==================== 1. דיווחים יומיים ====================
create table if not exists public.sales_hub_reports (
  id            bigint generated by default as identity,
  report_date   date not null default current_date,
  agent_id      bigint not null,
  hours         numeric not null default 0,
  dials         integer not null default 0,
  conversations integer not null default 0,
  offers        integer not null default 0,
  followups     integer not null default 0,
  deals         integer not null default 0,
  sales         numeric not null default 0,
  collected     numeric not null default 0,
  blockers      text,
  learning      text,
  created_by    uuid default auth.uid(),
  created_at    timestamptz not null default now()
);

-- אילוצים — בנפרד כדי שהרצה חוזרת לא תיכשל
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'sales_hub_reports_pkey') then
    alter table public.sales_hub_reports add constraint sales_hub_reports_pkey primary key (id);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'sales_hub_reports_agent_fkey') then
    alter table public.sales_hub_reports add constraint sales_hub_reports_agent_fkey
      foreign key (agent_id) references public.agents(id) on delete cascade;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'sales_hub_reports_day_uniq') then
    alter table public.sales_hub_reports add constraint sales_hub_reports_day_uniq unique (agent_id, report_date);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'sales_hub_reports_hours_check') then
    alter table public.sales_hub_reports add constraint sales_hub_reports_hours_check
      check (hours >= 0 and hours <= 24);
  end if;
end $$;

create index if not exists sales_hub_reports_date_idx on public.sales_hub_reports (report_date);

-- ==================== 2. מצב המוקד ====================
create table if not exists public.sales_hub_store (
  key        text primary key,
  data       jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

-- ==================== RLS: מנהל פעיל בלבד ====================
alter table public.sales_hub_reports enable row level security;
alter table public.sales_hub_store   enable row level security;

drop policy if exists sales_hub_reports_admin on public.sales_hub_reports;
create policy sales_hub_reports_admin on public.sales_hub_reports
  for all to authenticated
  using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.active and p.role = 'admin'))
  with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.active and p.role = 'admin'));

drop policy if exists sales_hub_store_admin on public.sales_hub_store;
create policy sales_hub_store_admin on public.sales_hub_store
  for all to authenticated
  using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.active and p.role = 'admin'))
  with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.active and p.role = 'admin'));

revoke all on public.sales_hub_reports from anon;
revoke all on public.sales_hub_store   from anon;
grant select, insert, update, delete on public.sales_hub_reports to authenticated;
grant select, insert, update, delete on public.sales_hub_store   to authenticated;
grant all on public.sales_hub_reports to service_role;
grant all on public.sales_hub_store   to service_role;

-- ==================== 3. מתג בהגדרות ====================
insert into public.settings (key, value) values ('sales_hub_enabled', '0')
  on conflict (key) do nothing;
