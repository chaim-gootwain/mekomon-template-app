-- ============================================================
-- מיגרציה: קישור מסמך ↔ מודעות (לשחזור בביטול מסמך)
-- ------------------------------------------------------------
-- בהפקת חשבונית נשמרות על המסמך המודעות שסומנו "חשבונית הופקה"
-- והשלב שהיה להן קודם (+ מצב "חויב מראש" של החוזה). ביטול חשבון
-- עסקה / זיכוי למסמך מס מחזיר אותן לשלב הקודם.
-- מבנה: {"ads":[{"id":123,"prev":"agreed"}], "contract":{"id":5,"prev_prepaid":false}}
-- הרצה: Supabase Dashboard → SQL Editor → הדבק והרץ, בכל מופע.
-- בטוח להרצה חוזרת (idempotent).
-- ============================================================

alter table public.documents add column if not exists ad_links jsonb;

comment on column public.documents.ad_links is
  'המודעות שהמסמך סימן "חשבונית הופקה" והשלב הקודם שלהן — לשחזור בביטול/זיכוי. NULL = מסמך ישן / ללא מודעות.';
