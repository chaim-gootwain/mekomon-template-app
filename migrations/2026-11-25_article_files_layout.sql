-- ============================================================
-- מיגרציה: קבצי כתבה + שליחה לגרפיקאית לעימוד
-- ------------------------------------------------------------
-- 1. article_files — כמה קבצים לכל כתבה (טקסט, תמונות, PDF...).
--    הקבצים עצמם בדלי ad-files תחת articles/<id>/ (מדיניות ה-storage
--    הקיימת מתירה העלאה לעורך/מנהל/גרפיקה וצפייה לכל הצוות).
-- 2. עמודות עימוד ב-articles: layout_status (null = לא נשלח,
--    sent = נשלח לגרפיקאית, in_layout = בעימוד, done = עומד),
--    layout_note (הנחיה לגרפיקאית), layout_sent_at.
-- 3. RPC לגרפיקה: graphics_articles() — רשימת הכתבות שנשלחו
--    לעימוד (בלי לפתוח לגרפיקה את כל טבלת הכתבות), ו-
--    graphics_article_set_layout() — סימון "בעימוד"/"עומד".
-- הרצה: Supabase Dashboard → SQL Editor → הדבק והרץ את כל הקובץ,
-- בכל מופע בנפרד. בטוח להרצה חוזרת (idempotent).
-- ============================================================

-- ---------- 1. עמודות עימוד ----------
alter table public.articles add column if not exists layout_status text;
alter table public.articles add column if not exists layout_note text;
alter table public.articles add column if not exists layout_sent_at timestamptz;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'articles_layout_status_check') then
    alter table public.articles add constraint articles_layout_status_check
      check (layout_status is null or layout_status in ('sent', 'in_layout', 'done'));
  end if;
end $$;

create index if not exists articles_layout_status_idx
  on public.articles (layout_status) where layout_status is not null;

-- ---------- 2. קבצי כתבה ----------
create table if not exists public.article_files (
  id bigint generated by default as identity,
  article_id bigint not null,
  storage_path text not null,
  file_name text,
  uploaded_by uuid default auth.uid(),
  created_at timestamptz not null default now()
);

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'article_files_pkey') then
    alter table public.article_files add constraint article_files_pkey primary key (id);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'article_files_article_fkey') then
    alter table public.article_files add constraint article_files_article_fkey
      foreign key (article_id) references public.articles(id) on delete cascade;
  end if;
end $$;

create index if not exists article_files_article_idx on public.article_files (article_id);

comment on table public.article_files is
  'קבצי כתבה (בדלי ad-files תחת articles/<id>/) — נשלחים לגרפיקאית לעימוד';

alter table public.article_files enable row level security;

-- מנהל/עורך: הכל. גרפיקה: קריאה בלבד, ורק לכתבות שנשלחו לעימוד.
drop policy if exists article_files_select on public.article_files;
create policy article_files_select on public.article_files
  for select to authenticated
  using (
    public.emu_active_staff(array['admin', 'editor'])
    or ( public.emu_active_staff(array['graphics'])
         and exists (select 1 from public.articles a
                     where a.id = article_id and a.layout_status is not null) )
  );

drop policy if exists article_files_write on public.article_files;
create policy article_files_write on public.article_files
  for all to authenticated
  using (public.emu_active_staff(array['admin', 'editor']))
  with check (public.emu_active_staff(array['admin', 'editor']));

grant all on public.article_files to authenticated, service_role;

-- ---------- 3. RPC לגרפיקה ----------
create or replace function public.graphics_articles(p_include_done boolean default false)
returns table (
  id bigint, title text, author text, section_name text, issue_id bigint,
  issue_number text, layout_status text, layout_note text, layout_sent_at timestamptz,
  est_length text, files jsonb
)
language sql stable security definer set search_path = public as $fn$
  select a.id::bigint, a.title::text,
         coalesce(nullif(a.author_name::text, ''), p.full_name::text),
         s.name::text, a.issue_id::bigint, i.issue_number::text,
         a.layout_status, a.layout_note, a.layout_sent_at, a.est_length::text,
         coalesce((select jsonb_agg(jsonb_build_object('path', f.storage_path, 'name', f.file_name) order by f.id)
                   from public.article_files f where f.article_id = a.id), '[]'::jsonb)
  from public.articles a
  left join public.profiles p on p.id = a.author_profile_id
  left join public.sections s on s.id = a.section_id
  left join public.issues i on i.id = a.issue_id
  where public.emu_active_staff(array['admin', 'editor', 'graphics'])
    and a.layout_status is not null
    and (p_include_done or a.layout_status <> 'done')
  order by a.layout_sent_at desc nulls last
  limit 200
$fn$;
revoke all on function public.graphics_articles(boolean) from public;
grant execute on function public.graphics_articles(boolean) to authenticated;

create or replace function public.graphics_article_set_layout(p_id bigint, p_status text)
returns void
language plpgsql security definer set search_path = public as $fn$
begin
  if not public.emu_active_staff(array['admin', 'editor', 'graphics']) then
    raise exception 'אין הרשאה';
  end if;
  if p_status not in ('in_layout', 'done') then
    raise exception 'סטטוס לא חוקי';
  end if;
  update public.articles set layout_status = p_status
   where id = p_id and layout_status is not null;
end
$fn$;
revoke all on function public.graphics_article_set_layout(bigint, text) from public;
grant execute on function public.graphics_article_set_layout(bigint, text) to authenticated;
