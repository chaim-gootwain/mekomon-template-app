-- ============================================================
-- מיגרציה: אחוז הנחה בהצעות מחיר
-- ------------------------------------------------------------
-- מוסיפה עמודה discount_pct לטבלת quotes כדי לשמור את אחוז ההנחה
-- שנבחר בטופס (כשמזינים הנחה ב-% ולא ב-₪). סכום ההנחה עצמו ממשיך
-- להישמר כרגיל בעמודה discount (₪), כך שהכל עובד גם בלי המיגרציה הזו —
-- העמודה רק מאפשרת לתייג את שורת ההנחה ב-PDF/בדף החתימה עם "(10%)".
-- הרצה: Supabase Dashboard → SQL Editor → הדבק והרץ את כל הקובץ.
-- בטוח להרצה חוזרת (IF NOT EXISTS).
-- ============================================================

alter table public.quotes
  add column if not exists discount_pct numeric;

comment on column public.quotes.discount_pct is
  'אחוז ההנחה שנבחר בטופס ההצעה (NULL כשההנחה הוזנה כסכום ₪ קבוע)';
